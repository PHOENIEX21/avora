import fs from 'node:fs';
const checks=[];const must=(ok,label)=>{checks.push([ok,label]);console.log(`${ok?'PASS':'FAIL'} ${label}`)};
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const migration=read('database/migrations/017_human_support.sql');
const student=read('components/SupportChat.tsx');
const admin=read('components/AdminSupportConsole.tsx');
const queue=read('app/admin/support/page.tsx');
const detail=read('app/admin/support/[id]/page.tsx');
const api=read('app/api/support/route.ts');
const messages=read('app/api/support/[id]/messages/route.ts');
for(const table of ['support_threads','support_messages','support_thread_events'])must(migration.includes(table),`database has ${table}`);
must(student.includes("setInterval")&&student.includes("5000"),'student support chat polls for near-live replies');
must(admin.includes("ASSIGN_SELF")&&admin.includes("PRIORITY")&&admin.includes("STATUS"),'admin can own, prioritize and manage cases');
must(queue.includes('Waiting on us')&&queue.includes('Priority'),'support inbox exposes operational queue signals');
must(detail.includes('Weakest current evidence')&&detail.includes('Recent supervised evidence'),'admin conversation includes learner academic context');
must(api.includes('tutor_topic_progress')&&api.includes('remediation_plans'),'new support request snapshots learning context');
must(messages.includes("senderRole=s.role==='ADMIN'?'ADMIN':'STUDENT'")&&messages.includes('WAITING_ON_SUPPORT'),'student/admin direct messaging changes queue state');
must(read('components/MobileNav.tsx').includes('/support')&&read('app/layout.tsx').includes("'/admin/support':'/support'"),'support is discoverable from signed-in navigation');
const failed=checks.filter(x=>!x[0]);console.log(`\nHuman Support audit: ${checks.length-failed.length}/${checks.length}`);if(failed.length)process.exit(1);

const css=read('app/globals.css');
const [maj,min]=String(pkg.version).split('.').map(Number);
check('release includes V14.6 flow/runtime work',maj===14&&min>=6);
check('Gemini schema normalizes unsupported anyOf unions',ai.includes('function geminiSchema')&&ai.includes('out.type=types'));
check('Tutor nullable reguideStepId uses Gemini-compatible type array',tutor.includes("reguideStepId:{type:['string','null']}"));
check('Gemini failures expose sanitized diagnostic detail server-side',ai.includes('safeProviderError')&&tutor.includes("ai.detail||''"));
check('trial countdown starts from server timestamp to prevent text hydration mismatch',trial.includes('initialNow')&&layout.includes('initialNow={renderedAt}'));
check('parent registration creates a session immediately',parentRegister.includes('createSession')&&parentRegister.includes("role:'PARENT'"));
check('parent registration continues directly to family setup',parentForm.includes("router.replace(d.next||'/parent/family')"));
check('parent can create a new learner from family setup',family.includes('<ParentCreateChild/>'));
check('parent can connect an existing learner by code',family.includes('<ParentLinkChild inline/>'));
check('learner can invite a parent by email',studentConnect.includes('/api/parent-link-code/invite')&&invite.includes('sendParentConnectionInvite'));
check('learner-parent invite still requires parent acceptance',invite.includes('sign in and accept the connection'));
check('parent mobile navigation points to real family and billing destinations',mobile.includes('href="/parent/family"')&&mobile.includes('href="/parent/billing"'));

import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const checks=[];const check=(name,ok)=>{checks.push([name,Boolean(ok)]);console.log(`${ok?'PASS':'FAIL'} — ${name}`)};
const pkg=JSON.parse(read('package.json'));
const ai=read('lib/aiGateway.ts');
const tutor=read('app/api/tutor/chat/route.ts');
const trial=read('components/TrialCountdownStrip.tsx');
const layout=read('app/layout.tsx');
const parentRegister=read('app/api/parent/register/route.ts');
const parentForm=read('components/ParentRegisterForm.tsx');
const studentConnect=read('components/StudentParentConnect.tsx');
const invite=read('app/api/parent-link-code/invite/route.ts');
const family=read('app/parent/family/page.tsx');
const mobile=read('components/MobileNav.tsx');

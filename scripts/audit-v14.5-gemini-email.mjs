import fs from 'node:fs';
let p=0,f=0;const ok=(n,v)=>{console.log(`${v?'PASS':'FAIL'} ${n}`);v?p++:f++};
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const gateway=fs.readFileSync('lib/aiGateway.ts','utf8');
const email=fs.readFileSync('lib/email.ts','utf8');
const reg=fs.readFileSync('app/api/auth/register/route.ts','utf8');
const parent=fs.readFileSync('app/api/parent/register/route.ts','utf8');
const resend=fs.readFileSync('app/api/auth/resend-verification/route.ts','utf8');
const tutor=fs.readFileSync('app/api/tutor/chat/route.ts','utf8');
const practice=fs.readFileSync('app/api/practice/explain/route.ts','utf8');
const exam=fs.readFileSync('app/api/exam/finish/route.ts','utf8');
const env=fs.readFileSync('.env.example','utf8');
const preflight=fs.readFileSync('scripts/preflight.mjs','utf8');
const migration=fs.readFileSync('database/migrations/032_ai_gateway_email_launch.sql','utf8');
ok('version 14.5.x or newer within major 14',/^14\.5\.\d+$/.test(pkg.version)||/^14\.(?:[6-9]|\d{2,})\.\d+$/.test(pkg.version));
ok('Gemini is default AI provider',env.includes('AI_PROVIDER="gemini"'));
ok('Gemini current configured default',gateway.includes("process.env.GEMINI_MODEL?.trim()||'gemini-3.6-flash'"));
ok('OpenAI fallback retained',gateway.includes("['gemini','openai']")&&gateway.includes('api.openai.com'));
ok('privacy stripping before provider call',gateway.includes('private account detail removed'));
ok('Gemini structured JSON supported',gateway.includes("responseMimeType:'application/json'")&&gateway.includes('responseSchema:geminiSchema(schema)'));
ok('learner signup creates verification token',reg.includes('createVerificationToken(user.id)'));
ok('learner signup sends verification email',reg.includes('sendVerificationEmail(user.email,user.full_name,token)'));
ok('learner signup survives email failure',reg.includes("catch(mailError)")&&reg.indexOf('createSession')<reg.indexOf('sendVerificationEmail'));
ok('parent signup sends verification email',parent.includes('sendVerificationEmail(user.email,user.full_name,token)'));
ok('resend verification preserved',resend.includes('sendVerificationEmail'));
ok('Brevo remains primary',email.indexOf('BREVO_API_KEY')<email.indexOf('SENDGRID_API_KEY'));
ok('Tutor uses AI gateway',tutor.includes('aiStructured')&&!tutor.includes('api.openai.com'));
ok('Practice uses AI gateway',practice.includes('aiStructured')&&!practice.includes('api.openai.com'));
ok('Exam graders use AI gateway',exam.includes('aiStructured')&&!exam.includes('api.openai.com'));
ok('AI provider/model usage migration',migration.includes('provider text')&&migration.includes('model text'));
ok('Preflight requires selected AI provider key',preflight.includes("required('GEMINI_API_KEY')")&&preflight.includes("required('OPENAI_API_KEY')"));
ok('Env documents Brevo',env.includes('BREVO_API_KEY')&&env.includes('EMAIL_FROM'));
ok('Env documents Gemini',env.includes('GEMINI_API_KEY')&&env.includes('GEMINI_MODEL'));
ok('Launch gate includes V14.5 audit after newer release gates',pkg.scripts['launch:check'].includes('npm run audit:v14.5-gemini-email'));
console.log(`\nV14.5 Gemini/email audit: ${p}/${p+f} PASS`);if(f)process.exit(1);

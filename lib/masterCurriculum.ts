export function masterTopics(classLevel:string,subject:string){
 if(isNerdc2025Class(classLevel))return nerdcRuntimeMasterTopics(classLevel,subject);
 return masterCurriculum.filter(x=>x.classLevel===classLevel&&x.subject===subject);
}
